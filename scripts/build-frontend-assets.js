#!/usr/bin/env node

import { mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname } from "node:path";
import { minify } from "terser";

const checkMode = process.argv.includes("--check");

const jsBuilds = [
  {
    input: "frontend/js/api-client.js",
    output: "frontend/js/api-client.min.js",
  },
  {
    input: "frontend/js/pages/index-page.js",
    output: "frontend/js/pages/index-page.min.js",
  },
  {
    input: "frontend/js/pages/pot-detail-page.js",
    output: "frontend/js/pages/pot-detail-page.min.js",
  },
];

const iconBuilds = [
  {
    output: "frontend/css/icons-home.css",
    label: "homepage",
    sources: [
      "frontend/index.html",
      "frontend/js/pages/index-page.js",
    ],
  },
  {
    output: "frontend/css/icons-pot-detail.css",
    label: "pot detail",
    sources: [
      "frontend/pot-detail.html",
      "frontend/js/pages/pot-detail-page.js",
    ],
  },
  {
    output: "frontend/css/icons-admin.css",
    label: "admin",
    sources: [
      "frontend/admin-plants.html",
      "frontend/admin-users.html",
      "frontend/admin-cache.html",
      "frontend/admin-stats.html",
      "frontend/admin-inbox.html",
    ],
  },
];

const iconSafelist = new Set([
  "fa-spin",
]);

function writeGeneratedFile(file, content) {
  if (checkMode) {
    const current = readFileSync(file, "utf8");
    if (current !== content) {
      throw new Error(`${file} is out of date. Run npm.cmd run build-frontend-assets.`);
    }
    return;
  }

  mkdirSync(dirname(file), { recursive: true });
  writeFileSync(file, content, "utf8");
}

async function buildMinifiedJs() {
  for (const build of jsBuilds) {
    const source = readFileSync(build.input, "utf8");
    const result = await minify(source, {
      compress: {
        passes: 2,
      },
      mangle: true,
      format: {
        comments: false,
      },
    });

    if (!result.code) {
      throw new Error(`Terser produced empty output for ${build.input}`);
    }

    writeGeneratedFile(build.output, `${result.code}\n`);
    console.log(`${checkMode ? "Verified" : "Minified"} ${build.input} -> ${build.output}`);
  }
}

function collectIconClasses(sources) {
  const classes = new Set(iconSafelist);
  const iconPattern = /\bfa-[a-z0-9-]+\b/g;

  for (const file of sources) {
    const source = readFileSync(file, "utf8");
    for (const match of source.matchAll(iconPattern)) {
      classes.add(match[0]);
    }
  }

  return classes;
}

function readCssBlocks(css) {
  const blocks = [];
  let index = 0;

  while (index < css.length) {
    const open = css.indexOf("{", index);
    if (open === -1) break;

    const selectorStart = css.lastIndexOf("}", open - 1) + 1;
    const selector = css.slice(selectorStart, open).trim();
    let depth = 1;
    let cursor = open + 1;

    while (cursor < css.length && depth > 0) {
      const char = css[cursor];
      if (char === "{") depth += 1;
      if (char === "}") depth -= 1;
      cursor += 1;
    }

    blocks.push({
      selector,
      text: css.slice(selectorStart, cursor).trim(),
    });
    index = cursor;
  }

  return blocks;
}

function buildIconCss(iconBuild) {
  const requiredIcons = collectIconClasses(iconBuild.sources);
  const source = readFileSync("frontend/css/icons.css", "utf8");
  const blocks = readCssBlocks(source);
  const availableIcons = new Set();
  const selectedBlocks = [];

  for (const block of blocks) {
    const blockIcons = new Set(block.text.match(/\bfa-[a-z0-9-]+\b/g) || []);
    for (const icon of blockIcons) {
      availableIcons.add(icon);
    }

    const isBaseIconRule = /(^|,\s*)\.(fa|fas|far|fal|fab)\b/.test(block.selector);
    const isRequiredIconRule = [...blockIcons].some((icon) => requiredIcons.has(icon));
    const isRequiredAnimation = block.selector === "@keyframes fa-spin" && requiredIcons.has("fa-spin");

    if (isBaseIconRule || isRequiredIconRule || isRequiredAnimation) {
      selectedBlocks.push(block.text);
    }
  }

  const missingIcons = [...requiredIcons].filter((icon) => !availableIcons.has(icon)).sort();
  if (missingIcons.length > 0) {
    throw new Error(`Missing icon definitions in frontend/css/icons.css: ${missingIcons.join(", ")}`);
  }

  const output = [
    "/* Generated by scripts/build-frontend-assets.js from frontend/css/icons.css. */",
    `/* Keep ${iconBuild.label} icon usage in sync with: ${iconBuild.sources.join(", ")}. */`,
    "",
    ...selectedBlocks.map(minifyCssBlock),
    "",
  ].join("\n");

  writeGeneratedFile(iconBuild.output, output);
  console.log(`${checkMode ? "Verified" : "Built"} ${iconBuild.output} with ${requiredIcons.size} ${iconBuild.label} icon classes`);
}

function minifyCssBlock(block) {
  return block
    .replace(/%3C%21--.*?--%3E/g, "")
    .replace(/\/\*[\s\S]*?\*\//g, "")
    .replace(/\s+/g, " ")
    .replace(/\s*([{}:;,])\s*/g, "$1")
    .replace(/;}/g, "}")
    .trim();
}

await buildMinifiedJs();
for (const iconBuild of iconBuilds) {
  buildIconCss(iconBuild);
}
